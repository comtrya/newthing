#!/usr/bin/env bash
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT_DIR"

SERVER_PID=""
FRONTEND_PID=""
SOURCE_GIT_PIDS=""
SOURCE_GIT_URL=""
TMP_DIR=""
