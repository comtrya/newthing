log() {
  printf '[comtrya] %s\n' "$*"
}

usage() {
  cat <<'USAGE'
Usage: ./start.sh [--reset] [--oneshot]

Options:
  --reset    Reset generated runtime repository, metadata, and extension storage before startup.
  --oneshot  Exit after the smoke checks pass.

Environment:
  COMTRYA_BROWSER_SMOKE=1  Run the headless browser extension smoke in interactive mode.
USAGE
}

fail() {
  printf '[comtrya] ERROR: %s\n' "$*" >&2
  for log_file in "${SERVER_LOG:-}" "${FRONTEND_LOG:-}"; do
    if [[ -n "$log_file" && -f "$log_file" ]]; then
      printf '\n[comtrya] %s tail:\n' "$log_file" >&2
      tail -n 80 "$log_file" >&2 || true
    fi
  done
  exit 1
}

require_command() {
  local command_name="$1"
  command -v "$command_name" >/dev/null 2>&1 || fail "missing required command: $command_name"
}

reset_generated_path() {
  local path="$1"
  case "$path" in
    "$DATA_DIR"/*)
      if [[ -e "$path" ]]; then
        log "resetting generated path: $path"
        rm -rf -- "$path"
      fi
      ;;
    *)
      fail "refusing to reset path outside COMTRYA_DATA_DIR: $path"
      ;;
  esac
}

create_smoke_source_repo() {
  local repo_dir="$1"
  mkdir -p "$repo_dir/cue.mod" "$repo_dir/docs/rfcs" "$repo_dir/crates/server" "$repo_dir/frontend/src"
  git -C "$repo_dir" init --initial-branch=main >/dev/null 2>&1 \
    || git -C "$repo_dir" init >/dev/null 2>&1
  git -C "$repo_dir" config user.name "Comtrya Smoke"
  git -C "$repo_dir" config user.email "smoke@comtrya.local"
  # Fixture commits must never depend on the operator's signing setup. An
  # operator with commit signing forced in their global git config (e.g.
  # gitsign/Sigstore) would otherwise see these throwaway scaffolding commits
  # block on interactive OAuth, failing the documented acceptance path.
  git -C "$repo_dir" config commit.gpgsign false
  git -C "$repo_dir" config tag.gpgsign false
  if [[ "$(git -C "$repo_dir" branch --show-current)" != "main" ]]; then
    git -C "$repo_dir" checkout -B main >/dev/null 2>&1
  fi

  cat >"$repo_dir/README.md" <<'EOF'
# Comtrya Smoke Repository

This repository is generated by start.sh and imported through the product API.
EOF
  cat >"$repo_dir/cue.mod/module.cue" <<'EOF'
module: "comtrya.dev/smoke"
language: version: "v0.10.0"
EOF
  cat >"$repo_dir/comtrya.cue" <<'EOF'
package comtrya

// Per-repo extension opt-in (#137 / Phase 2). Repository-scoped extension
// features (issues, pulls, checks) and the issue→epic part-of participation
// gate are off unless the repo opts in via `repository.extensions`. The smoke
// exercises all four, so it enables them here. Authored without the published
// schema import because the imported smoke repo doesn't vendor that CUE module;
// the kernel reads `repository.extensions` as a plain array.
repository: extensions: ["ext_issues", "ext_pull_requests", "ext_checks", "ext_epics", "ext_sprints"]

projects: kernel: {
	root: "."
	labels: ["runtime"]
}
EOF
  cat >"$repo_dir/docs/rfcs/0001-runtime-smoke.md" <<'EOF'
---
title: Runtime Smoke
---

Imported through createRepository during the end-to-end smoke.
EOF
  cat >"$repo_dir/crates/server/lib.rs" <<'EOF'
pub fn smoke_marker() -> &'static str {
    "runtime"
}
EOF
  git -C "$repo_dir" add .
  git -C "$repo_dir" commit -m "initial smoke repository" >/dev/null

  git -C "$repo_dir" checkout -b ui/repository-intelligence >/dev/null
  cat >"$repo_dir/frontend/src/panel.ts" <<'EOF'
export const panel = "repository-intelligence";
EOF
  git -C "$repo_dir" add .
  git -C "$repo_dir" commit -m "add repository intelligence branch" >/dev/null
  git -C "$repo_dir" checkout main >/dev/null
}

# `createRepository` clones the source over HTTP only — `file://` and `git://`
# are rejected as SSRF/local-disclosure vectors. Serve the source repo's object
# store over dumb Smart-HTTP (a static file server is sufficient for a
# `git clone --bare`) so the import path exercises a real network clone.
# Sets SOURCE_GIT_URL to the served base URL and appends the server PID to
# SOURCE_GIT_PIDS for cleanup. Safe to call more than once (smoke source +
# dogfood snapshot each get their own server).
serve_git_source_over_http() {
  local repo_dir="$1"
  local git_root="$repo_dir/.git"
  [[ -d "$git_root" ]] || git_root="$repo_dir"
  # Dumb HTTP transport reads the static refs/packs advertisement.
  git --git-dir="$git_root" update-server-info

  local server_js="$TMP_DIR/git-source-server.mjs"
  cat >"$server_js" <<'EOF'
const ROOT = process.env.GIT_HTTP_ROOT;
Bun.serve({
  hostname: process.env.GIT_HTTP_HOST ?? "127.0.0.1",
  port: Number(process.env.GIT_HTTP_PORT),
  async fetch(req) {
    const rel = decodeURIComponent(new URL(req.url).pathname);
    if (rel.includes("..")) return new Response("bad request", { status: 400 });
    const file = Bun.file(ROOT + rel);
    if (await file.exists()) return new Response(file);
    return new Response("not found", { status: 404 });
  },
});
EOF

  # Pick an unused high port WITHOUT killing whatever might be on it. Unlike
  # the fixed kernel/frontend ports that `free_port` reclaims from a prior
  # run, this is an ephemeral helper port chosen at random, so killing the
  # current listener could take down an unrelated local process. Probe with
  # lsof and retry on collision instead.
  local host="127.0.0.1"
  local port=""
  local candidate
  for _ in $(seq 1 50); do
    candidate="$((24000 + RANDOM % 20000))"
    if ! lsof -nP -iTCP@"$host:$candidate" -sTCP:LISTEN >/dev/null 2>&1; then
      port="$candidate"
      break
    fi
  done
  [[ -n "$port" ]] || fail "could not find a free port for the git source server"
  GIT_HTTP_ROOT="$git_root" GIT_HTTP_HOST="$host" GIT_HTTP_PORT="$port" \
    "$BUN" "$server_js" >"$TMP_DIR/git-source-http-$port.log" 2>&1 &
  SOURCE_GIT_PIDS="$SOURCE_GIT_PIDS $!"
  SOURCE_GIT_URL="http://$host:$port/"
  wait_for_url "git source http ($port)" "http://$host:$port/info/refs" 200
}

cleanup() {
  for pid in $SOURCE_GIT_PIDS "$FRONTEND_PID" "$SERVER_PID"; do
    if [[ -n "$pid" ]] && kill -0 "$pid" >/dev/null 2>&1; then
      log "stopping pid=$pid"
      kill "$pid" >/dev/null 2>&1 || true
      wait "$pid" >/dev/null 2>&1 || true
    fi
  done
  if [[ -n "$TMP_DIR" && -d "$TMP_DIR" ]]; then
    rm -rf "$TMP_DIR"
  fi
}

load_envrc() {
  if [[ ! -f "$ROOT_DIR/.envrc" ]]; then
    return
  fi

  local override_names=(
    BUN
    COMTRYA_BROWSER_SMOKE
    COMTRYA_CONFIG_REPO_REF
    COMTRYA_CONFIG_REPO_URL
    COMTRYA_DATA_DIR
    COMTRYA_EXTENSION_DIR
    COMTRYA_FRONTEND_LISTEN
    COMTRYA_FRONTEND_URL
    COMTRYA_LISTEN
    COMTRYA_ONESHOT
    COMTRYA_OPERATOR_CODE
    COMTRYA_READY_TIMEOUT_SECONDS
    COMTRYA_RESET_DATA
    COMTRYA_SERVER_URL
    COMTRYA_SESSION_TTL_SECONDS
    PUBLIC_COMTRYA_OPERATOR_CODE
  )
  for name in "${override_names[@]}"; do
    eval "SNAP_${name}_SET=\"\${${name}+1}\""
    eval "SNAP_${name}_VALUE=\"\${${name}-}\""
  done

  if command -v direnv >/dev/null 2>&1; then
    eval "$(direnv export bash)"
  else
    log ".envrc found but direnv is unavailable; attempting plain shell source"
    set +e
    set -a
    # shellcheck disable=SC1091
    source "$ROOT_DIR/.envrc"
    local rc=$?
    set +a
    set -e
    if [[ "$rc" -ne 0 ]]; then
      fail ".envrc could not be loaded without direnv"
    fi
  fi

  for name in "${override_names[@]}"; do
    local set_marker
    eval "set_marker=\"\${SNAP_${name}_SET}\""
    if [[ -n "$set_marker" ]]; then
      eval "export ${name}=\"\${SNAP_${name}_VALUE}\""
    fi
  done
}

expect_status() {
  local label="$1"
  local expected="$2"
  local body_file="$3"
  shift 3

  local status
  status="$(curl -sS -o "$body_file" -w '%{http_code}' "$@")" || fail "$label request failed"
  if [[ "$status" != "$expected" ]]; then
    printf '\n[comtrya] %s returned HTTP %s, expected %s\n' "$label" "$status" "$expected" >&2
    printf '[comtrya] response body:\n' >&2
    sed -n '1,180p' "$body_file" >&2 || true
    exit 1
  fi
  log "ok - $label ($status)"
}

expect_contains() {
  local label="$1"
  local body_file="$2"
  local needle="$3"

  if ! grep -Fq "$needle" "$body_file"; then
    printf '\n[comtrya] %s response did not contain: %s\n' "$label" "$needle" >&2
    printf '[comtrya] response body:\n' >&2
    sed -n '1,180p' "$body_file" >&2 || true
    exit 1
  fi
}

# `/events` and `/graphql/stream` are real, open-ended `text/event-stream`
# responses (15s keep-alives), so a plain GET never returns. The backfill
# frames are flushed immediately on connect, so we read for a bounded window,
# then disconnect — `curl --max-time` exits 28 on the timeout, which is the
# expected, successful path here. Captures the streamed frames into a file for
# a follow-up `expect_contains`.
read_event_stream() {
  local label="$1"
  local body_file="$2"
  shift 2

  curl -sS --no-buffer --max-time 5 -o "$body_file" "$@" >/dev/null 2>&1 || true
  if [[ ! -s "$body_file" ]]; then
    printf '\n[comtrya] %s produced no event-stream frames within the read window\n' "$label" >&2
    exit 1
  fi
  log "ok - $label (streamed)"
}

json_assert() {
  local label="$1"
  local body_file="$2"
  local expression="$3"

  if ! "$BUN" --eval '
const fs = require("fs");
const [file, expression, label] = process.argv.slice(1);
let json;
try {
  json = JSON.parse(fs.readFileSync(file, "utf8"));
} catch (error) {
  console.error(`[comtrya] ${label} did not return valid JSON: ${error.message}`);
  process.exit(1);
}
let ok = false;
try {
  ok = Boolean(Function("json", `"use strict"; return (${expression});`)(json));
} catch (error) {
  console.error(`[comtrya] ${label} JSON assertion threw: ${error.message}`);
  console.error(`[comtrya] assertion: ${expression}`);
  process.exit(1);
}
if (!ok) {
  console.error(`[comtrya] ${label} JSON assertion failed: ${expression}`);
  console.error(JSON.stringify(json, null, 2).slice(0, 12000));
  process.exit(1);
}
' "$body_file" "$expression" "$label"; then
    exit 1
  fi
}

