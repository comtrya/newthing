const json = JSON.parse(fs.readFileSync(file, "utf8"));
const value = Function("json", `"use strict"; return (${expression});`)(json);
if (value !== undefined && value !== null) {
  process.stdout.write(String(value));
}
' "$body_file" "$expression"
}

